package com.denisnumb.buildtools;

import org.gradle.api.DefaultTask;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.provider.MapProperty;
import org.gradle.api.provider.Property;
import org.gradle.api.tasks.Input;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.TaskAction;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Pattern;

public abstract class GenerateBuildConstantsTask extends DefaultTask {
    private static final Pattern JAVA_NAME = Pattern.compile("[A-Za-z_$][A-Za-z0-9_$]*");

    @Input
    public abstract Property<String> getPackageName();

    @Input
    public abstract Property<String> getClassName();

    @Input
    public abstract MapProperty<String, String> getConstants();

    @OutputDirectory
    public abstract DirectoryProperty getOutputDirectory();

    public GenerateBuildConstantsTask() {
        setGroup("build");
        setDescription("Generates a class with constants from gradle.properties.");
        getClassName().convention("BuildConstants");
    }

    @TaskAction
    public void generate() throws IOException {
        String packageName = getPackageName().get();
        String className = getClassName().get();
        validate(className);

        StringBuilder sb = new StringBuilder()
                .append("package ").append(packageName).append(";\n\n")
                .append("// Generated by the ").append(getName())
                .append(" Gradle task from gradle.properties. Do not edit manually.\n")
                .append("public final class ").append(className).append(" {\n")
                .append("    private ").append(className).append("() {}\n");

        for (Map.Entry<String, String> constant : new TreeMap<>(getConstants().get()).entrySet()) {
            validate(constant.getKey());
            sb.append("\n    public static final String ").append(constant.getKey())
                    .append(" = \"").append(escape(constant.getValue())).append("\";\n");
        }
        sb.append("}\n");

        Path outDir = getOutputDirectory().get().getAsFile().toPath();
        Path packageDir = outDir.resolve(packageName.replace('.', '/'));
        if (Files.exists(outDir)) {
            try (var files = Files.walk(outDir)) {
                files.sorted(java.util.Comparator.reverseOrder())
                        .filter(path -> !path.equals(outDir))
                        .forEach(path -> path.toFile().delete());
            }
        }
        Files.createDirectories(packageDir);
        Files.writeString(packageDir.resolve(className + ".java"), sb.toString(), StandardCharsets.UTF_8);
    }

    private static void validate(String name) {
        if (!JAVA_NAME.matcher(name).matches())
            throw new IllegalArgumentException("Not a valid Java identifier: " + name);
    }

    private static String escape(String value) {
        StringBuilder sb = new StringBuilder();
        for (char c : value.toCharArray()) {
            switch (c) {
                case '\\' -> sb.append("\\\\");
                case '"' -> sb.append("\\\"");
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                case '\t' -> sb.append("\\t");
                default -> {
                    if (c < 0x20 || c > 0x7e)
                        sb.append(String.format("\\u%04x", (int) c));
                    else
                        sb.append(c);
                }
            }
        }
        return sb.toString();
    }
}